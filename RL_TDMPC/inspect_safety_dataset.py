#!/usr/bin/env python3
"""Strictly validate and inspect an offline Safety auxiliary dataset."""

from __future__ import annotations

import argparse
import json
from pathlib import Path
from typing import Optional, Sequence

from tdmpc2.safety_aux_dataset import load_dataset


def parse_args(argv: Optional[Sequence[str]] = None) -> argparse.Namespace:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "dataset_path",
        nargs="?",
        type=Path,
        help="Dataset generated by collect_safety_dataset.py",
    )
    parser.add_argument(
        "--dataset",
        dest="dataset_option",
        type=Path,
        help="Dataset path (alternative to the positional argument)",
    )
    parser.add_argument(
        "--compact",
        action="store_true",
        help="Print one-line JSON instead of indented JSON",
    )
    args = parser.parse_args(argv)
    if (args.dataset_path is None) == (args.dataset_option is None):
        parser.error(
            "provide exactly one dataset path, either positionally or with "
            "--dataset"
        )
    args.dataset = (
        args.dataset_path
        if args.dataset_path is not None
        else args.dataset_option
    )
    return args


def main(argv: Optional[Sequence[str]] = None) -> None:
    args = parse_args(argv)
    dataset = load_dataset(args.dataset)
    summary = dataset.summary()
    print(
        json.dumps(
            summary,
            indent=None if args.compact else 2,
            sort_keys=True,
            allow_nan=False,
        )
    )


if __name__ == "__main__":
    main()
